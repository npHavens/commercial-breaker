var rule = GeminiConfirmation()
assert(!rule.accept("program", end: 10))
assert(rule.count == 1 && rule.confirmed == nil)
assert(rule.accept("program", end: 15) && rule.confirmed == .program)
assert(!rule.accept("commercial", end: 20) && rule.confirmed == .program)
assert(!rule.accept("program", end: 25) && rule.confirmed == .program)
assert(!rule.accept("commercial", end: 30))
assert(rule.accept("promo", end: 35) && rule.confirmed == .commercialBreak)
assert(!rule.accept("program", end: 40))
assert(!rule.accept("unclear", end: 45) && rule.count == 0)
assert(rule.display.contains("Last confirmed") && rule.display.contains("unclear"))
assert(!rule.accept("program", end: 50))
assert(rule.accept("program", end: 55))
assert(!rule.accept("commercial", end: 80) && rule.confirmed == nil)
assert(!rule.accept("commercial", end: 80) && rule.lastEnd == nil)
assert(!rule.accept("program", end: .nan))
rule.reset()
assert(rule.confirmed == nil && rule.count == 0)
print("Confirmation checks passed: isolated flips, promo grouping, unclear, gaps, duplicate timestamps, reset")

rule.reset()
assert(!rule.accept("commercial", end: 1))
assert(!rule.accept("unclear", end: 6) && rule.needsFastFollowUp)
assert(!rule.accept("unclear", end: 7) && rule.count == 0)
assert(!rule.accept("commercial", end: 8))
assert(rule.accept("promo", end: 9))
rule.reset()
assert(!rule.accept("commercial", end: 1))
assert(!rule.accept("unclear", end: 10))
assert(!rule.accept("commercial", end: 17) && rule.count == 1)
assert(rule.accept("commercial", end: 18))
rule.reset()
assert(!rule.accept("commercial", end: 1))
assert(!rule.accept("unclear", end: 2))
assert(!rule.accept("program", end: 3) && rule.count == 1)
assert(!rule.accept("program", end: 4))
assert(rule.accept("program", end: 8))
print("Unclear bridging checks passed: expiry, repeated unclear, opposing evidence")

rule.reset()
assert(!rule.accept("commercial", end: 1))
assert(rule.accept("commercial", end: 2))
assert(!rule.accept("program", end: 3) && !rule.needsFastFollowUp)
assert(!rule.accept("program", end: 4))
assert(!rule.accept("unclear", end: 5) && rule.count == 0)
assert(!rule.accept("program", end: 6))
assert(!rule.accept("program", end: 10.9))
assert(rule.accept("program", end: 11))
print("Program returns require uninterrupted evidence and at least five fresh seconds")

for negative in ["not_program", "unusable"] {
