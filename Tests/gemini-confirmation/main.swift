import Foundation
var rule = GeminiConfirmation()
assert(!rule.accept("program", end: 10))
assert(rule.count == 1 && rule.confirmed == nil)
assert(rule.accept("program", end: 15) && rule.confirmed == .program)
assert(!rule.accept("commercial", end: 20) && rule.confirmed == .program)
assert(!rule.accept("program", end: 25) && rule.confirmed == .program)
assert(!rule.accept("commercial", end: 30))
assert(rule.accept("promo", end: 35) && rule.confirmed == .commercialBreak)
assert(!rule.accept("program", end: 40))
assert(!rule.accept("unclear", end: 45) && rule.count == 0)
assert(rule.display.contains("Last confirmed") && rule.display.contains("unclear"))
assert(!rule.accept("program", end: 50))
assert(rule.accept("program", end: 55))
assert(!rule.accept("commercial", end: 80) && rule.confirmed == nil)
assert(!rule.accept("commercial", end: 80) && rule.lastEnd == nil)
assert(!rule.accept("program", end: .nan))
rule.reset()
assert(rule.confirmed == nil && rule.count == 0)
print("Confirmation checks passed: isolated flips, promo grouping, unclear, gaps, duplicate timestamps, reset")

rule.reset()
assert(!rule.accept("commercial", end: 1))
assert(!rule.accept("unclear", end: 6) && rule.needsFastFollowUp)
assert(!rule.accept("unclear", end: 7) && rule.count == 0)
assert(!rule.accept("commercial", end: 8))
assert(rule.accept("promo", end: 9))
rule.reset()
assert(!rule.accept("commercial", end: 1))
assert(!rule.accept("unclear", end: 10))
assert(!rule.accept("commercial", end: 17) && rule.count == 1)
assert(rule.accept("commercial", end: 18))
rule.reset()
assert(!rule.accept("commercial", end: 1))
assert(!rule.accept("unclear", end: 2))
assert(!rule.accept("program", end: 3) && rule.count == 1)
assert(!rule.accept("program", end: 4))
assert(rule.accept("program", end: 8))
print("Unclear bridging checks passed: expiry, repeated unclear, opposing evidence")

rule.reset()
assert(!rule.accept("commercial", end: 1))
assert(rule.accept("commercial", end: 2))
assert(!rule.accept("program", end: 3) && !rule.needsFastFollowUp)
assert(!rule.accept("program", end: 4))
assert(!rule.accept("unclear", end: 5) && rule.count == 0)
assert(!rule.accept("program", end: 6))
assert(!rule.accept("program", end: 10.9))
assert(rule.accept("program", end: 11))
print("Program returns require uninterrupted evidence and at least five fresh seconds")

for negative in ["not_program", "unusable"] {
    rule.reset()
    assert(!rule.accept("program", end: 1))
    assert(!rule.accept(negative, end: 6) && rule.count == 0)
    assert(!rule.accept("program", end: 11))
    assert(rule.accept("program", end: 16))
    assert(rule.confirmed == .program)
}
print("Binary negatives and unusable audio reset return evidence without confirming a break")

// A break needs one commercial among its matching predictions; promos alone hold the candidate.
rule.reset()
assert(!rule.accept("promo", end: 1) && rule.needsFastFollowUp)
assert(!rule.accept("promo", end: 2) && rule.count == 2 && rule.confirmed == nil)
assert(rule.display.contains("Promo only"))
assert(!rule.accept("promo", end: 6) && rule.confirmed == nil)
assert(rule.accept("commercial", end: 9) && rule.confirmed == .commercialBreak)
assert(rule.display.hasPrefix("Confirmed"))
// Either order confirms at the second prediction, as before.
for pair in [["promo", "commercial"], ["commercial", "promo"]] {
    rule.reset()
    assert(!rule.accept(pair[0], end: 1))
    assert(rule.accept(pair[1], end: 2) && rule.confirmed == .commercialBreak)
}
// A commercial from an earlier candidate does not carry over to a new one.
rule.reset()
assert(!rule.accept("commercial", end: 1))
assert(!rule.accept("program", end: 2))
assert(!rule.accept("promo", end: 3))
assert(!rule.accept("promo", end: 4) && rule.confirmed == nil && !rule.commercialHeard)
// Promos alone never end a confirmed program, and program returns are unchanged.
rule.reset()
assert(!rule.accept("program", end: 1))
assert(rule.accept("program", end: 6) && rule.confirmed == .program)
assert(!rule.accept("promo", end: 7))
assert(!rule.accept("promo", end: 8) && rule.confirmed == .program)
// A held promo-only candidate bridges one unclear sample, like a one-prediction candidate.
rule.reset()
assert(!rule.accept("promo", end: 1))
assert(!rule.accept("promo", end: 2))
assert(!rule.accept("unclear", end: 7) && rule.count == 2)
assert(rule.accept("commercial", end: 12) && rule.confirmed == .commercialBreak)
// Clearing a candidate through unclear samples or an evidence gap also clears the commercial.
rule.reset()
assert(!rule.accept("commercial", end: 1))
assert(!rule.accept("unclear", end: 2))
assert(!rule.accept("unclear", end: 3) && rule.candidate == nil && !rule.commercialHeard)
assert(!rule.accept("promo", end: 4))
assert(!rule.accept("promo", end: 5) && rule.confirmed == nil)
rule.reset()
assert(!rule.accept("commercial", end: 1))
assert(!rule.accept("unclear", end: 10))
assert(!rule.accept("unclear", end: 20) && !rule.commercialHeard)
// Promos after a confirmed break do not claim to be waiting to confirm one.
rule.reset()
assert(!rule.accept("commercial", end: 1))
assert(rule.accept("promo", end: 2))
assert(!rule.accept("program", end: 3))
assert(!rule.accept("promo", end: 4))
assert(!rule.accept("promo", end: 5) && rule.confirmed == .commercialBreak)
assert(!rule.display.contains("Promo only"))
print("Promo-only candidates wait for a commercial before confirming a break")
