import Foundation

var policy = AutomaticCommercialPolicy()
assert(policy.phase == .idle)
assert(policy.confirmed(.commercialBreak) == .none)
assert(policy.begin())
assert(!policy.begin())
assert(policy.confirmed(.commercialBreak) == .none)
assert(!policy.reachedMac())
assert(policy.startedOnTV())
assert(!policy.startedOnTV())
assert(policy.confirmed(.program) == .none)

assert(policy.confirmed(.commercialBreak) == .toMac)
assert(policy.phase == .movingToMac)
assert(policy.confirmed(.commercialBreak) == .none)
assert(policy.confirmed(.program) == .none)
assert(!policy.reachedTV())
assert(policy.reachedMac())
assert(policy.phase == .mutedMac)
assert(!policy.reachedMac())
assert(policy.confirmed(.commercialBreak) == .none)

assert(policy.confirmed(.program) == .toTV)
assert(policy.confirmed(.program) == .none)
assert(policy.confirmed(.commercialBreak) == .none)
assert(policy.reachedTV())
assert(policy.phase == .watchingTV)

// Recovery and stop reject completions while idle or recovering. The controller's
// generation check additionally rejects earlier asynchronous sessions.
assert(policy.confirmed(.commercialBreak) == .toMac)
policy.recover()
assert(policy.phase == .recovering)
assert(!policy.reachedMac())
assert(policy.confirmed(.program) == .none)
assert(policy.confirmed(.commercialBreak) == .none)
policy.stop()
assert(policy.phase == .idle)
assert(!policy.reachedTV())
assert(policy.begin())
policy.stop()
assert(!policy.startedOnTV())
policy.recover()
assert(policy.phase == .idle)
print("Automatic policy checks passed: verified completions, duplicate predictions, recovery, cancellation")

assert(policy.begin())
assert(policy.startedOnMac())
assert(policy.confirmed(.program) == .none)
assert(policy.confirmed(.commercialBreak) == .muteLocal)
assert(policy.confirmed(.commercialBreak) == .none)
assert(!policy.reachedMac())
assert(policy.mutedLocally())
assert(policy.phase == .mutedLocalMac)
assert(policy.confirmed(.commercialBreak) == .none)
assert(policy.confirmed(.program) == .unmuteLocal)
assert(!policy.reachedTV())
assert(policy.unmutedLocally())
assert(policy.phase == .watchingMac)
assert(policy.confirmed(.commercialBreak) == .muteLocal)
policy.recover()
assert(!policy.mutedLocally())
assert(policy.confirmed(.program) == .none)
policy.stop()
assert(!policy.unmutedLocally())
print("Local automatic mute cycle, duplicate guards and recovery checks passed")

assert(!policy.localMuteLimitReached())
assert(!policy.localLimitReleased())
assert(policy.begin())
assert(policy.startedOnMac())
assert(!policy.localMuteLimitReached())
assert(policy.confirmed(.commercialBreak) == .muteLocal)
assert(policy.mutedLocally())
assert(policy.localMuteLimitReached())
assert(!policy.localMuteLimitReached())
assert(policy.confirmed(.program) == .none)
assert(policy.localLimitReleased())
assert(policy.phase == .awaitingLocalProgram)
for _ in 0..<5 { assert(policy.confirmed(.commercialBreak) == .none) }
assert(policy.phase == .awaitingLocalProgram)
assert(policy.confirmed(.program) == .none)
assert(policy.phase == .watchingMac)
assert(policy.confirmed(.commercialBreak) == .muteLocal)
assert(policy.mutedLocally())
assert(policy.localMuteLimitReached())
policy.recover()
assert(!policy.localLimitReleased())
assert(policy.confirmed(.program) == .none)
policy.stop()
assert(!policy.localLimitReleased())
print("Mute timeout checks passed: release, no same-break remute, program rearm, recovery guards")

var pickerRecovery = AutomaticCommercialPolicy()
assert(!pickerRecovery.pickerUnavailable())
pickerRecovery.begin(); pickerRecovery.startedOnTV()
assert(pickerRecovery.confirmed(.commercialBreak) == .toMac)
assert(pickerRecovery.pickerUnavailable())
assert(pickerRecovery.phase == .watchingTV)
assert(!pickerRecovery.reachedMac()) // Reject a stale handoff completion.
assert(pickerRecovery.confirmed(.program) == .none)
assert(pickerRecovery.confirmed(.commercialBreak) == .toMac)
assert(pickerRecovery.reachedMac())
assert(pickerRecovery.confirmed(.program) == .toTV)
assert(pickerRecovery.pickerUnavailable())
assert(pickerRecovery.phase == .audibleMacAwaitingTV)
assert(!pickerRecovery.reachedTV())
assert(pickerRecovery.confirmed(.commercialBreak) == .none)
assert(pickerRecovery.confirmed(.program) == .toTV)
assert(pickerRecovery.reachedTV())
pickerRecovery.recover()
assert(!pickerRecovery.pickerUnavailable())
assert(pickerRecovery.confirmed(.commercialBreak) == .none)
pickerRecovery.stop()
assert(!pickerRecovery.pickerUnavailable())
print("Picker recovery checks passed: both directions, stale completions, recovery and stop guards")

var longBreak = AutomaticCommercialPolicy()
assert(!longBreak.airPlayLimitReleased())
longBreak.begin(); longBreak.startedOnTV()
assert(longBreak.confirmed(.commercialBreak) == .toMac)
assert(!longBreak.airPlayLimitReleased()) // Still routing, not yet muted.
longBreak.reachedMac()
assert(longBreak.airPlayLimitReleased())
assert(longBreak.phase == .audibleMacAwaitingTV)
assert(!longBreak.airPlayLimitReleased())
for _ in 0..<5 { assert(longBreak.confirmed(.commercialBreak) == .none) }
assert(longBreak.confirmed(.program) == .toTV)
assert(!longBreak.airPlayLimitReleased())
assert(longBreak.reachedTV())
assert(longBreak.confirmed(.commercialBreak) == .toMac) // Next break still works.
longBreak.recover()
assert(!longBreak.airPlayLimitReleased())
longBreak.stop()
assert(!longBreak.airPlayLimitReleased())
print("AirPlay long-break checks passed: audible waiting, no repeated mute, program return, next break, stale completions")
